/** UI 内建中英双语字典；当前首批只承诺 zh-CN 与 en-US。 */
export const JWORD_UI_BUILTIN_I18N_DICTIONARIES: Readonly<Record<JWordStatusBarLocale, JWordUiI18nDictionary>> = Object.freeze({
  'zh-CN': ZH_CN_UI_I18N_DICTIONARY,
  'en-US': EN_US_UI_I18N_DICTIONARY
})

/** UI 内建默认中文字典。 */
export const DEFAULT_JWORD_UI_I18N_DICTIONARY: JWordUiI18nDictionary = ZH_CN_UI_I18N_DICTIONARY

/** 合并默认字典与宿主局部覆盖。 */
export function resolveJWordUiI18n(options: JWordUiI18nOptions | undefined = undefined): ResolvedJWordUiI18n {
  const messages: JWordUiI18nDictionary = Object.freeze({
    ...readBuiltInLocaleDictionary(options?.locale),
    ...(options?.messages ?? {})
  })

  return {
    locale: options?.locale ?? 'zh-CN',
    ...(options?.dir === undefined ? {} : { dir: options.dir }),
    messages,
    t(key, fallback): string {
      return readJWordUiText({ messages }, key, fallback)
    }
  }
}

/** 读取字典文案，缺失或空字符串时回退到既有文案。 */
export function readJWordUiText(
  i18n: Pick<ResolvedJWordUiI18n, 'messages'>,
  key: JWordUiI18nKey,
  fallback: string
): string {
  const value = i18n.messages[key]

  return value === undefined || value.length === 0 ? fallback : value
}

/** 按 i18n 字典本地化单个内建 toolbar 定义。 */
export function localizeToolbarDefinition(
  definition: BuiltinToolDefinition,
  i18n: ResolvedJWordUiI18n
): BuiltinToolDefinition {
  return {
    ...definition,
    label: readJWordUiText(i18n, `toolbar.${definition.id}.label`, definition.label),
    tooltip: readJWordUiText(i18n, `toolbar.${definition.id}.tooltip`, definition.tooltip),
    ...(definition.fieldLabel === undefined
      ? {}
      : { fieldLabel: readJWordUiText(i18n, `toolbar.${definition.id}.fieldLabel`, definition.fieldLabel) }),
    ...(definition.options === undefined
      ? {}
      : { options: definition.options.map((option) => localizeToolbarOption(definition.id, option, i18n)) })
  }
}

/** 本地化 toolbar option 文案。 */
function localizeToolbarOption(
  toolId: BuiltinToolDefinition['id'],
  option: ToolbarOption,
  i18n: ResolvedJWordUiI18n
): ToolbarOption {
  return {
    ...option,
    label: readJWordUiText(i18n, `toolbar.${toolId}.option.${readToolbarOptionKey(option.value)}`, option.label)
  }
}

/** 根据当前 locale 读取内建字典，不支持的 locale 回退中文。 */
function readBuiltInLocaleDictionary(locale: string | undefined): JWordUiI18nDictionary {
  return locale === 'en-US'
    ? JWORD_UI_BUILTIN_I18N_DICTIONARIES['en-US']
    : JWORD_UI_BUILTIN_I18N_DICTIONARIES['zh-CN']
}

/** 从当前 toolbar 内建定义生成完整中文字典，避免遗漏旧工具文案。 */
function createBuiltInToolbarDictionary(): JWordUiI18nDictionary {
  const dictionary: Record<string, string> = {}

  for (const toolId of BUILTIN_TOOL_IDS) {
    const definition = getBuiltinToolDefinition(toolId)

    dictionary[`toolbar.${toolId}.label`] = definition.label
    dictionary[`toolbar.${toolId}.tooltip`] = definition.tooltip
    if (definition.fieldLabel !== undefined) {
      dictionary[`toolbar.${toolId}.fieldLabel`] = definition.fieldLabel
    }

    for (const option of definition.options ?? []) {
      dictionary[`toolbar.${toolId}.option.${readToolbarOptionKey(option.value)}`] = option.label
    }
  }

  return dictionary as JWordUiI18nDictionary
}

/** 将 option value 转成稳定字典 key 片段。 */
function readToolbarOptionKey(value: string): string {
  if (value === '') {
    return 'empty'
  }

  if (value === '__mixed__') {
    return 'mixed'
  }

  return value
}
